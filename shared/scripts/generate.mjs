/**
 * Contract codegen pipeline:
 * 1) dump OpenAPI -> shared/openapi/openapi.json
 * 2) openapi-typescript -> shared/generated/openapi.ts
 *
 * Usage:
 *   npm run generate
 *   npm run generate:from-url
 *   node ./scripts/generate.mjs --from-url --url http://127.0.0.1:8000/openapi.json
 */

import { spawnSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const sharedRoot = path.resolve(__dirname, '..')
const openapiFile = path.join(sharedRoot, 'openapi', 'openapi.json')
const generatedDir = path.join(sharedRoot, 'generated')
const generatedFile = path.join(generatedDir, 'openapi.ts')

function runNodeScript(scriptName, extraArgs) {
  const scriptPath = path.join(__dirname, scriptName)
  const result = spawnSync(process.execPath, [scriptPath, ...extraArgs], {
    cwd: sharedRoot,
    encoding: 'utf8',
    stdio: 'inherit',
  })
  if (result.status !== 0) {
    process.exit(result.status ?? 1)
  }
}

function runOpenapiTypescript() {
  mkdirSync(generatedDir, { recursive: true })
  // Prefer the package entry over .cmd shim to avoid shell:true on Windows.
  const cliEntry = path.join(
    sharedRoot,
    'node_modules',
    'openapi-typescript',
    'bin',
    'cli.js',
  )

  const result = spawnSync(process.execPath, [cliEntry, openapiFile, '-o', generatedFile], {
    cwd: sharedRoot,
    encoding: 'utf8',
    stdio: 'inherit',
  })

  if (result.status !== 0) {
    throw new Error('openapi-typescript failed. Run npm install in shared/ first.')
  }
}

function writeGeneratedReadme() {
  const notePath = path.join(generatedDir, 'README.md')
  writeFileSync(
    notePath,
    [
      '# generated/',
      '',
      'Auto-generated by `npm run generate`. Do not edit by hand.',
      '',
      '| File | Description |',
      '|------|-------------|',
      '| `openapi.ts` | From `openapi/openapi.json` via openapi-typescript |',
      '',
      'Regenerate:',
      '',
      '```bash',
      'npm run generate',
      '```',
      '',
    ].join('\n'),
    'utf8',
  )
}

function main() {
  const extraArgs = process.argv.slice(2)
  runNodeScript('dump-openapi.mjs', extraArgs)
  runOpenapiTypescript()
  writeGeneratedReadme()
  console.log(`TypeScript types generated: ${path.relative(sharedRoot, generatedFile)}`)
}

try {
  main()
} catch (error) {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
}
